package app.reelify.navigation

import android.net.Uri

object Routes {
    const val SPLASH = "splash"
    const val MAIN = "main"
    const val SETUP = "setup?treatment={treatment}&style={style}"
    fun setup(treatment: String? = null, style: String? = null) = "setup?treatment=${treatment.orEmpty()}&style=${style.orEmpty()}"
    const val IDEA = "idea/{pid}"
    fun idea(pid: String) = "idea/$pid"
    const val FEEDBACK = "feedback/{pid}"
    fun feedback(pid: String) = "feedback/$pid"
    const val SCRIPT = "script/{pid}"
    fun script(pid: String) = "script/$pid"
    const val CHECKLIST = "checklist/{pid}"
    fun checklist(pid: String) = "checklist/$pid"
    const val RECORD = "record/{pid}/{sid}?role={role}"
    fun record(pid: String, sid: String, role: String = "PRIMARY") = "record/$pid/$sid?role=$role"
    const val REVIEW = "review/{pid}"
    fun review(pid: String) = "review/$pid"
    const val TRIM = "trim/{cid}"
    fun trim(cid: String) = "trim/$cid"
    const val AUTOEDIT = "autoedit/{pid}?force={force}"
    fun autoEdit(pid: String, force: Boolean = false) = "autoedit/$pid?force=$force"
    const val PREVIEW = "preview/{pid}"
    fun preview(pid: String) = "preview/$pid"
    const val EDITOR = "editor/{pid}"
    fun editor(pid: String) = "editor/$pid"
    const val CAPTIONS = "captions/{pid}"
    fun captions(pid: String) = "captions/$pid"
    const val EXPORT = "export/{pid}"
    fun export(pid: String) = "export/$pid"
    const val TREATMENT = "treatment/{id}"
    fun treatment(id: String) = "treatment/${Uri.encode(id)}"
    const val BRANDING = "branding"
    const val TERMINOLOGY = "terminology"
    const val AI_SETTINGS = "ai-settings"
    const val STORAGE = "storage"
    const val LIBRARY = "library"
    const val LICENSES = "licenses"
}
